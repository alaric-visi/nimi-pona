/**
 * Extract sitelen pona glyphs from the nasin nanpa font into SVG path data.
 *
 *   node scripts/build-glyphs.mjs
 *
 * Output: src/data/glyphs.json, committed, so the app needs no font at runtime and
 * every glyph can be animated stroke by stroke. Re-run after changing the font or words.yaml.
 * Font: nasin nanpa by jan Itan, MIT licence (assets/fonts/nasin-nanpa-LICENSE.txt).
 */
import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'node:fs';
import { parse } from 'yaml';

const FONT = 'assets/fonts/nasin-nanpa-4.0.2-UCSUR.otf';
const OUT = 'src/data/glyphs.json';
const SIZE = 100; // render at 100 units/em: one decimal place is plenty of precision

const buf = readFileSync(FONT);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const byName = new Map();
for (let i = 0; i < font.numGlyphs; i++) {
  const g = font.glyphs.get(i);
  if (g.name) byName.set(g.name, g);
}

const words = parse(readFileSync('content/words.yaml', 'utf8'));
const scale = SIZE / font.unitsPerEm;
const baseline = font.ascender * scale; // y of the baseline once flipped into SVG space

const glyphs = {};
const missing = [];
for (const w of words) {
  const key = w.glyph ?? w.id;
  const g = byName.get(`${key}Tok`);
  if (!g) {
    missing.push(key);
    continue;
  }
  const path = g.getPath(0, baseline, SIZE);
  const box = path.getBoundingBox();
  const r = (n) => Math.round(n * 10) / 10;
  glyphs[key] = {
    d: path.toPathData(1),
    // tight box around the ink, so glyphs centre optically regardless of side bearings
    box: [r(box.x1), r(box.y1), r(box.x2 - box.x1), r(box.y2 - box.y1)],
  };
}

if (missing.length) {
  console.error(`No glyph in ${FONT} for: ${missing.join(', ')}`);
  process.exit(1);
}

const out = {
  source: 'nasin nanpa 4.0.2 by jan Itan (MIT). Generated by scripts/build-glyphs.mjs; do not edit.',
  em: SIZE,
  glyphs,
};
writeFileSync(OUT, JSON.stringify(out) + '\n');
console.log(`wrote ${Object.keys(glyphs).length} glyphs → ${OUT} (${(JSON.stringify(out).length / 1024).toFixed(1)} KB)`);
